def a(attr, amount, op="add_value"):
    return {"attribute": f"minecraft:{attr}", "amount": amount, "operation": op}


def pct(attr, amount):
    return a(attr, amount, "add_multiplied_base")


def node(name, desc, attrs=(), **perks):
    return {"name": name, "desc": desc, "attrs": list(attrs), "perks": perks}


