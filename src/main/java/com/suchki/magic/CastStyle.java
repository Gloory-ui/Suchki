package com.suchki.magic;

/**
 * Как творится заклинание: от этого зависят зарядка, анимация рук и эффекты у руки.
 * Все, кроме CHANNEL, сначала заряжаются (накопление маны), потом выпускаются.
 */
public enum CastStyle {
	/** Снаряд или удар по прицелу: замах, рука по взгляду, толчок вперёд. */
	BOLT,
	/** Поток: держишь — работает, мана уходит каждую секунду. */
	CHANNEL,
	/** На себя: руки к груди, на выпуске раскрываются. */
	SELF,
	/** Ритуал: руки над головой, круг на земле, удар вниз. */
	RITUAL,
	/** Призыв: фокус над головой, взмах вниз-вперёд. */
	SUMMON;

	public boolean charged() {
		return this != CHANNEL;
	}
}
