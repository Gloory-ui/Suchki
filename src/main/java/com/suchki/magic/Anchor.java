package com.suchki.magic;

/**
 * Где строится магический круг, пока маг копит силу. От этого же зависит, откуда вылетают копии мультикаста.
 * Точка прицела — до {@link Spell#range} блоков (по умолчанию до {@link Magic#MAX_RANGE}).
 */
public enum Anchor {
	/** Стоит вертикально перед посохом, смотрит по взгляду (снаряды, лучи). */
	HAND,
	/** Лежит на земле под ногами мага (заклинания на себя, вокруг себя, призыв рядом). */
	FEET,
	/** Лежит на земле в точке прицела (удары по месту, ловушки, зоны). */
	TARGET,
	/** Висит в небе над точкой прицела, смотрит вниз (метеоры, столпы, молнии с неба). */
	SKY,
	/** Ряд кругов от посоха к цели (ствол рейлгана, «Взрыв» Мегумин). */
	LINE,
	/** Веер небольших кругов за спиной мага («Врата Вавилона», копья). */
	BACK,
	/** Круги летают по орбите вокруг мага. */
	ORBIT;

	/** Круг привязан к точке прицела (его надо пересчитывать по взгляду). */
	public boolean targeted() {
		return this == TARGET || this == SKY || this == LINE;
	}
}
